#!/usr/bin/env python3
"""Write the native port's dispatch table: routine address -> hand-written C.

    python tools/hand_table.py s4 port/src/hand_table_s4.c

With every routine of a dump hand-written (c/hand/<ver>/hand.txt), the
port can run the game from that C alone (port/src/native_driver.c). Jump
tables and other computed transfers (r816_call_pc) then need the function
for an address; this table lists each routine variant with the register
widths (m, x) it was written for. The file holds addresses and names only.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    ver, out = sys.argv[1], sys.argv[2]
    rows, seen = [], set()
    for line in open(os.path.join(ROOT, 'c', 'hand', ver, 'hand.txt')):
        t = line.split('#')[0].split()
        if len(t) < 5:
            continue
        pc, m, x, name = int(t[0], 16), int(t[1]), int(t[2]), t[4]
        if (pc, m, x) in seen:
            continue
        seen.add((pc, m, x))
        rows.append((pc, m, x, '%s_m%dx%d' % (name, m, x)))
    rows.sort()
    fns = sorted({r[3] for r in rows})
    lines = ['/* Generated by tools/hand_table.py %s: routine address -> hand-written C */' % ver,
             '/* (c/hand/%s/hand.txt). Addresses and names only. */' % ver,
             '#include "hand_table.h"', '']
    lines += ['void %s(void);' % f for f in fns]
    lines += ['', 'const HandEntry g_hand_table[] = {']
    lines += ['    { 0x%06X, %d, %d, %s },' % r for r in rows]
    lines += ['};', 'const int g_hand_table_count = %d;' % len(rows), '']
    open(out, 'w', newline='\n').write('\n'.join(lines))
    print('%s: %d entries' % (out, len(rows)))


if __name__ == '__main__':
    main()
