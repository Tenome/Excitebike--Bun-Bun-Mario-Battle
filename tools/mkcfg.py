#!/usr/bin/env python3
"""Turn bsdis.py's code.json into snesrecomp bank cfg seeds.

    python tools/mkcfg.py build/s1/code.json recomp/s1 [--names config/s1/names.txt]

One bankXX.cfg per bank with a `func` line per discovered entry; entries that
are reached with several M/X states get one `entry_mx_at`-free func line (the
analyzer forks variants itself) and the first state as the declared width.
names.txt (optional): lines of `<pc24 hex> <name>` to give routines real names.
"""
import argparse
import collections
import json
import os


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('code_json')
    ap.add_argument('outdir')
    ap.add_argument('--names')
    ap.add_argument('--into', action='store_true',
                    help='outdir is a snesrecomp project recomp/ dir: replace the bsdis block in each bankNN.cfg')
    a = ap.parse_args()
    code = json.load(open(a.code_json))
    funcs = code['funcs']
    names = {}
    if a.names and os.path.exists(a.names):
        for line in open(a.names):
            line = line.split('#')[0].split()
            if len(line) >= 2:
                names[int(line[0].replace(':', ''), 16)] = line[1]
    by_bank = collections.defaultdict(list)
    for k, mx in funcs.items():
        pc = int(k, 16)
        if 0x80FFA0 <= pc < 0x80FFB0:
            continue    # vector JML stubs: the scaffold keeps these on the interpreter
        by_bank[pc >> 16].append((pc, mx))
    os.makedirs(a.outdir, exist_ok=True)
    for bank, items in sorted(by_bank.items()):
        if a.into:
            write_block(a.outdir, bank, items, names, code)
            continue
        lines = ['bank = %02X' % (bank & 0x7F)]
        if bank == 0x80:
            lines.append('auto_vectors')
        for pc, mx in sorted(items):
            m, x = int(mx[0][1]), int(mx[0][3])
            nm = names.get(pc, 'sub_%06X' % pc)
            lines.append('func %s %06X entry_mx:%d,%d' % (nm, pc, m, x))
        path = os.path.join(a.outdir, 'bank%02X.cfg' % (bank & 0x7F))
        with open(path, 'w') as f:
            f.write('\n'.join(lines) + '\n')
        print('wrote', path, len(items), 'funcs')


BEGIN = '# >>> BEGIN bsdis (generated by tools/mkcfg.py, do not edit)'
END = '# <<< END bsdis'


def dispatch_lines(code, bank):
    """indirect_dispatch directives for the jump tables bsdis resolved in this bank."""
    out = []
    insn = code.get('insn', {})
    for site, jt in sorted(code.get('jt', {}).items()):
        pc = int(site, 16)
        if (pc >> 16) != bank:
            continue
        ins = insn.get(site)
        tg = []
        for t in jt['targets']:
            if t not in tg:
                tg.append(t)
        if not ins or not tg:
            continue
        mn, mode = ins[0], ins[1]
        if mode == 'iabs' and mn == 'JMP':
            out.append('indirect_dispatch %04X %d ptrtail targets:%s' % (
                pc & 0xFFFF, len(tg), ','.join(t[2:] for t in tg)))
        elif mode == 'iabsx':
            out.append('indirect_dispatch %04X %d idx:X' % (pc & 0xFFFF, len(jt['targets'])))
    return out


def write_block(outdir, bank, items, names, code=None):
    path = os.path.join(outdir, 'bank%02x.cfg' % (bank & 0x7F))
    nl = chr(10)
    if os.path.exists(path):
        text = open(path).read()
    else:
        text = 'bank = %d' % (bank & 0x7F) + nl
    if BEGIN in text:
        pre = text[:text.index(BEGIN)]
        post = text[text.index(END) + len(END):].lstrip(nl)
    else:
        pre, post = text.rstrip(nl) + nl + nl, ''
    block = [BEGIN]
    for pc, mx in sorted(items):
        m, x = int(mx[0][1]), int(mx[0][3])
        block.append('func %s %06X entry_mx:%d,%d' % (names.get(pc, 'sub_%06X' % pc), pc, m, x))
    if code is not None:
        block.extend(dispatch_lines(code, bank))
    block.append(END)
    with open(path, 'w') as f:
        f.write(pre + nl.join(block) + nl + (post and nl + post))
    print('updated', path, len(items), 'funcs')


if __name__ == '__main__':
    main()
