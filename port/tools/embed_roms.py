#!/usr/bin/env python3
"""Build the ROM data into the executable, so it runs with no dump beside it.

    python port/tools/embed_roms.py genb --rom <s4.sfc> [--dump <other.sfc> ...]
    python port/tools/embed_roms.py gena --rom <s1.sfc>

Writes, for the target, port/src/embed/<target>/:
  bunbun_embedded.c   the dumps the target reads, as C arrays
  editor_courses.js   every course of both engines, decoded, for the course
                      editor (tools/editor/course_editor.html), which then opens
                      them without a ROM

Which dumps a target wants:  gena  s1.sfc
                             genb  s4.sfc (the boot image), s3.sfc (Luigi),
                                   s1.sfc (Stadium 1-2 courses)
Dumps are found by their SHA-256 among --rom, --dump, the files beside --rom,
$BUNBUN_DUMPS and the data/ folders of the build trees. A missing optional
dump only drops that feature, as before.

Everything written here is derived from the player's own ROM: the folder is
git-ignored and an executable built with it must not be shared.
"""
import argparse
import glob
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PORT = os.path.dirname(HERE)
ROOT = os.path.dirname(PORT)
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import course  # noqa: E402  (the course decoder: tools/course.py)

KNOWN = {
    'a22163ddd3d07f01101e885297568d1863db0639e5b1b97fc84dff253dee2089': 's1.sfc',
    '072e053c3fa74fc954b0b1b6e11bdee7219f6323be97abf869f7da3c11ca9247': 's3.sfc',
    'd689aacff0aa4b6357ff23de592980b286464be774f6bcdeea7da07d39de00ea': 's4.sfc',
}
WANT = {'gena': ['s1.sfc'], 'genb': ['s4.sfc', 's3.sfc', 's1.sfc']}
# course tables: start, length, data base, RUN bit
TABLES = {'A': (0x818C59, 0x818C6D, 0x818C81, 0x40), 'B': (0x818C62, 0x818C76, 0x818C8A, 0x80)}


def read_dump(path):
    try:
        b = open(path, 'rb').read()
    except OSError:
        return None
    if len(b) % 0x8000 == 512:
        b = b[512:]
    return b if len(b) == 0x100000 else None


def find_dumps(paths):
    found = {}
    for p in paths:
        b = read_dump(p)
        if b is None:
            continue
        name = KNOWN.get(hashlib.sha256(b).hexdigest())
        if name and name not in found:
            found[name] = (p, b)
    return found


def candidates(a):
    c = [a.rom] + a.dump
    if a.rom:
        d = os.path.dirname(os.path.abspath(a.rom))
        c += sorted(glob.glob(os.path.join(d, '*.sfc')) + glob.glob(os.path.join(d, '*.smc')))
    env = os.environ.get('BUNBUN_DUMPS')
    if env:
        c += sorted(glob.glob(os.path.join(env, '*.sfc')))
    c += sorted(glob.glob(os.path.join(PORT, 'build*', '**', 'data', '*.sfc'), recursive=True))
    return [p for p in c if p]


def rd16(rom, a):
    return course.rd(rom, a) | course.rd(rom, a + 1) << 8


def decode_all(rom, engine):
    st, ln, db, run = TABLES[engine]
    out = []
    for i in range(10):
        cols, _ = course.decode(rom, db, rd16(rom, st + 2 * i), rd16(rom, ln + 2 * i), run)
        out.append(bytes(cols))
    return out


def write_c(path, dumps):
    with open(path, 'w', newline='\n') as f:
        f.write('/* Generated by port/tools/embed_roms.py from the player\'s own dumps.\n'
                ' * Derived from copyrighted ROM data: never commit, never share. */\n'
                '#include <stddef.h>\n#include "bunbun_embedded.h"\n\n')
        names = []
        for i, (name, data) in enumerate(dumps):
            sym = 'kEmbed%d' % i
            names.append((name, sym))
            f.write('static const unsigned char %s[%d] = {\n' % (sym, len(data)))
            for k in range(0, len(data), 64):
                f.write(','.join(str(x) for x in data[k:k + 64]))
                f.write(',\n')
            f.write('};\n')
        f.write('\nconst BunbunEmbeddedDump kBunbunEmbedded[] = {\n')
        for name, sym in names:
            f.write('    { "%s", %s, sizeof %s },\n' % (name, sym, sym))
        f.write('    { NULL, NULL, 0 }\n};\n')


def write_js(path, courses):
    import base64
    with open(path, 'w', newline='\n') as f:
        f.write('/* Generated by port/tools/embed_roms.py: the original courses, decoded.\n'
                ' * Derived from the player\'s own ROM. Never commit, never share. */\n')
        f.write('window.BUNBUN_COURSES = {\n')
        for eng, lst in courses.items():
            f.write('  %s: [%s],\n' % (eng, ', '.join('"%s"' % base64.b64encode(c).decode() for c in lst)))
        f.write('};\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('target', choices=sorted(WANT))
    ap.add_argument('--rom', default='')
    ap.add_argument('--dump', action='append', default=[])
    a = ap.parse_args()
    found = find_dumps(candidates(a))
    boot = WANT[a.target][0]
    if boot not in found:
        print('embed_roms: %s not found; the executable will read data/ instead' % boot)
        return 0
    dumps = [(n, found[n][1]) for n in WANT[a.target] if n in found]
    out = os.path.join(PORT, 'src', 'embed', a.target)
    os.makedirs(out, exist_ok=True)
    write_c(os.path.join(out, 'bunbun_embedded.c'), dumps)
    courses = {}
    if 's1.sfc' in found:
        courses['A'] = decode_all(found['s1.sfc'][1], 'A')
    if 's4.sfc' in found:
        courses['B'] = decode_all(found['s4.sfc'][1], 'B')
    write_js(os.path.join(out, 'editor_courses.js'), courses)
    print('embed_roms: %s: %s; editor courses for engine %s' % (
        a.target, ', '.join(n for n, _ in dumps), '+'.join(sorted(courses)) or 'none'))
    missing = [n for n in WANT[a.target] if n not in found]
    if missing:
        print('embed_roms: not found (features that need them stay off): %s' % ', '.join(missing))
    return 0


if __name__ == '__main__':
    sys.exit(main())
